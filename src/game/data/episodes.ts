type L = [string, string];
function EC(
  id: string,
  title: string,
  who: [string, string],
  spot: string,
  at: string,
  duration: number,
  lines: L[],
): ConversationDef {
  return { id, title, who, spot, at: t(at), duration, lines: lines.map(([w, text]) => ({ who: w, text })) };
}

